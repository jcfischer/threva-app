import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";

interface RuntimeDependency {
  name: string;
  version: string;
}

export interface NoticesEntry extends RuntimeDependency {
  licence: string;
  text: string;
}

const licenceFiles = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md", "license"];

const header = [
  "# Third-party notices",
  "",
  "Threva is licensed AGPL-3.0-only; the full text is in [LICENSE](LICENSE). This file lists every",
  "package the UI's bundle can include: the `dependencies` of `package.json` and every package those",
  "depend on, resolved through `node_modules`, each with the licence text the package ships.",
  "Dev-only packages are not bundled and are not listed here.",
  "",
  "Generated by `bun run notices` from `node_modules`. `bun run check` fails when a package the",
  "bundle can include is missing from this file, when its version or licence text is out of date,",
  "or when a package is listed that the bundle can no longer include.",
  "",
].join("\n");

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function parseJson(text: string): unknown {
  const value: unknown = JSON.parse(text);
  return value;
}

function readManifest(path: string): Record<string, unknown> {
  const parsed = parseJson(readFileSync(path, "utf8"));
  if (!isRecord(parsed)) throw new Error(`${path} does not hold a JSON object`);
  return parsed;
}

function declaredNames(manifest: Record<string, unknown>, field: string): string[] {
  const declared = manifest[field];
  if (declared === undefined) return [];
  if (!isRecord(declared)) throw new Error(`package.json has a ${field} field that is not an object`);
  return Object.keys(declared).sort((a, b) => a.localeCompare(b));
}

function resolveInstalled(root: string, from: string, name: string): string | undefined {
  let directory = from;
  for (;;) {
    const candidate = join(directory, "node_modules", name, "package.json");
    if (existsSync(candidate)) return dirname(candidate);
    const parent = dirname(directory);
    if (directory === root || parent === directory) return undefined;
    directory = parent;
  }
}

interface InstalledPackage extends RuntimeDependency {
  directory: string;
}

function installedRuntimePackages(root: string): InstalledPackage[] {
  const manifest = readManifest(join(root, "package.json"));
  const queue = declaredNames(manifest, "dependencies").map((name) => ({ name, from: root }));
  const visited = new Set<string>();
  const packages = new Map<string, InstalledPackage>();
  while (queue.length > 0) {
    const next = queue.shift();
    if (next === undefined) break;
    const directory = resolveInstalled(root, next.from, next.name);
    if (directory === undefined) throw new Error(`node_modules/${next.name} is missing; run bun install`);
    if (visited.has(directory)) continue;
    visited.add(directory);
    const installed = readManifest(join(directory, "package.json"));
    const name = typeof installed.name === "string" ? installed.name : next.name;
    const version = typeof installed.version === "string" ? installed.version : "";
    if (version === "") throw new Error(`${directory}/package.json declares no version`);
    packages.set(`${name} ${version}`, { name, version, directory });
    for (const child of declaredNames(installed, "dependencies")) queue.push({ name: child, from: directory });
  }
  return [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

export function noticeEntries(root: string): NoticesEntry[] {
  return installedRuntimePackages(root).map(({ name, version, directory }) => {
    const installed = readManifest(join(directory, "package.json"));
    const licence = typeof installed.license === "string" ? installed.license : "";
    if (licence === "") throw new Error(`node_modules/${name}/package.json declares no license`);
    const file = licenceFiles.map((candidate) => join(directory, candidate)).find((path) => existsSync(path));
    if (file === undefined) throw new Error(`node_modules/${name} ships no licence file`);
    return { name, version, licence, text: readFileSync(file, "utf8").trimEnd() };
  });
}

export function renderEntry(entry: NoticesEntry): string {
  return `## ${entry.name} ${entry.version}\n\nLicense: ${entry.licence}\n\n\`\`\`\n${entry.text}\n\`\`\`\n`;
}

export function renderNotices(entries: NoticesEntry[]): string {
  return [header, ...entries.map(renderEntry)].join("\n");
}

function listedHeadings(notices: string): string[] {
  const lines = notices.split("\n");
  const headings: string[] = [];
  let fenced = false;
  for (const [index, line] of lines.entries()) {
    if (line.startsWith("```")) {
      fenced = !fenced;
      continue;
    }
    if (fenced || !line.startsWith("## ")) continue;
    if (lines[index + 1] !== "" || !(lines[index + 2] ?? "").startsWith("License: ")) continue;
    headings.push(line.slice("## ".length));
  }
  return headings;
}

export function noticesProblems(notices: string, entries: NoticesEntry[]): string[] {
  const missing = entries
    .filter((entry) => !notices.includes(renderEntry(entry)))
    .map((entry) => `THIRD-PARTY-NOTICES.md is missing ${entry.name} ${entry.version} (${entry.licence}) or its full licence text; run bun run notices`);
  const stale = listedHeadings(notices)
    .filter((heading) => !entries.some((entry) => heading.startsWith(`${entry.name} `)))
    .map((heading) => `THIRD-PARTY-NOTICES.md lists ${heading}, which is not a runtime dependency; run bun run notices`);
  return [...missing, ...stale];
}
