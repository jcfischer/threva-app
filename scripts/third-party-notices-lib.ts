import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

export interface RuntimeDependency {
  name: string;
  version: string;
}

export interface NoticesEntry extends RuntimeDependency {
  licence: string;
  text: string;
}

const licenceFiles = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md", "license"];

const header = [
  "# Third-party notices",
  "",
  "Threva is licensed AGPL-3.0-only; the full text is in [LICENSE](LICENSE). This file lists",
  "every runtime dependency of the built UI with the licence text that package ships.",
  "Dev-only packages are not bundled and are not listed here.",
  "",
  "Generated by `bun run notices` from `node_modules`. `bun run check` fails when a package in",
  "`dependencies` is missing from this file, when its version or licence text is out of date,",
  "or when a package is listed that is no longer a runtime dependency.",
  "",
].join("\n");

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function parseJson(text: string): unknown {
  const value: unknown = JSON.parse(text);
  return value;
}

function readManifest(path: string): Record<string, unknown> {
  const parsed = parseJson(readFileSync(path, "utf8"));
  if (!isRecord(parsed)) throw new Error(`${path} does not hold a JSON object`);
  return parsed;
}

export function dependencyNames(manifest: unknown): string[] {
  if (!isRecord(manifest)) throw new Error("package.json does not hold a JSON object");
  const dependencies = manifest.dependencies;
  if (dependencies === undefined) return [];
  if (!isRecord(dependencies)) throw new Error("package.json has a dependencies field that is not an object");
  return Object.keys(dependencies).sort((a, b) => a.localeCompare(b));
}

export function noticeEntries(root: string): NoticesEntry[] {
  const manifest = readManifest(join(root, "package.json"));
  return dependencyNames(manifest).map((name) => {
    const installed = readManifest(join(root, "node_modules", name, "package.json"));
    const version = typeof installed.version === "string" ? installed.version : "";
    const licence = typeof installed.license === "string" ? installed.license : "";
    if (version === "") throw new Error(`node_modules/${name}/package.json declares no version`);
    if (licence === "") throw new Error(`node_modules/${name}/package.json declares no license`);
    const file = licenceFiles.map((candidate) => join(root, "node_modules", name, candidate)).find((path) => existsSync(path));
    if (file === undefined) throw new Error(`node_modules/${name} ships no licence file`);
    return { name, version, licence, text: readFileSync(file, "utf8").trimEnd() };
  });
}

export function renderEntry(entry: NoticesEntry): string {
  return `## ${entry.name} ${entry.version}\n\nLicense: ${entry.licence}\n\n\`\`\`\n${entry.text}\n\`\`\`\n`;
}

export function renderNotices(entries: NoticesEntry[]): string {
  return [header, ...entries.map(renderEntry)].join("\n");
}

function listedNames(notices: string): string[] {
  return notices
    .split("\n")
    .filter((line) => line.startsWith("## "))
    .map((line) => line.slice("## ".length));
}

export function noticesProblems(notices: string, entries: NoticesEntry[]): string[] {
  const missing = entries
    .filter((entry) => !notices.includes(renderEntry(entry)))
    .map((entry) => `THIRD-PARTY-NOTICES.md is missing ${entry.name} ${entry.version} (${entry.licence}) or its full licence text; run bun run notices`);
  const stale = listedNames(notices)
    .filter((heading) => !entries.some((entry) => heading.startsWith(`${entry.name} `)))
    .map((heading) => `THIRD-PARTY-NOTICES.md lists ${heading}, which is not a runtime dependency; run bun run notices`);
  return [...missing, ...stale];
}
